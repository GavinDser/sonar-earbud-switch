import os
import tomllib

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CONFIG_PATH = os.path.join(ROOT, "config.toml")

DEFAULTS = {
    "earbuds": {"driver": "rog_cetra_open", "output": "", "mic": ""},
    "switching": {"force_on_takeout": False},
    "timing": {
        "takeout_debounce": 0.5,
        "unknown_state_delay": 6.0,
        "putback_debounce": 1.0,
        "retry": 3.0,
    },
    "volume_keys": {"enabled": True, "step": 0.02},
    "osd": {"enabled": True, "x": 50, "y": 50, "duration": 1.5},
}


def load(path=CONFIG_PATH):
    with open(path, "rb") as f:
        user = tomllib.load(f)
    cfg = {k: dict(v) for k, v in DEFAULTS.items()}
    for section, values in user.items():
        cfg.setdefault(section, {}).update(values)
    return cfg


def _q(s):
    return '"' + str(s).replace("\\", "\\\\").replace('"', '\\"') + '"'


def write(cfg, path=CONFIG_PATH):
    e, s, t, v, o = cfg["earbuds"], cfg["switching"], cfg["timing"], cfg["volume_keys"], cfg["osd"]
    text = f"""# sonar-earbud-switch 配置 / config（由 setup 生成，可手改 / generated by setup, editable）
# 放回仓时切到哪个设备由 Sonar 自己的设备优先级列表决定。
# Where audio goes when the earbuds are put away is decided by Sonar's own device priority list.

[earbuds]            # 耳机 / earbuds；名称关键字，不区分大小写 / name keyword, case-insensitive
driver = {_q(e["driver"])}
output = {_q(e["output"])}
mic = {_q(e["mic"])}

[switching]
# 取出时强制切到耳机（不管 Sonar 列表里有没有更高优先级的设备开着）
# Always switch to the earbuds on take-out, even if a higher-priority device is on
force_on_takeout = {str(s["force_on_takeout"]).lower()}

[timing]             # 秒 / seconds
takeout_debounce = {t["takeout_debounce"]}     # 取出后多久生效 / delay after take-out
unknown_state_delay = {t["unknown_state_delay"]}  # 仓内状态未知时连上多久才算取出 / when in-case state is unknown
putback_debounce = {t["putback_debounce"]}     # 放回仓/断开后多久生效 / delay after put-away
retry = {t["retry"]}                # 失败重试间隔 / retry interval

[volume_keys]        # 耳机在用时音量键调 Sonar 所有通道 / volume keys scale all Sonar channels
enabled = {str(v["enabled"]).lower()}
step = {v["step"]}

[osd]                # 屏幕提示 / on-screen indicator
enabled = {str(o["enabled"]).lower()}
x = {o["x"]}
y = {o["y"]}
duration = {o["duration"]}
"""
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(text)
